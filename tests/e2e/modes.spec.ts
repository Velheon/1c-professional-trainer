import { test, expect } from '@playwright/test'
test('random selection persists, bookmarks filter, review and draft stay manual',async({page})=> {
  await page.goto('/')
  await page.getByLabel('Импортировать архив',{exact:true}).setInputFiles('platform_83_export.zip')
  await expect(page.locator('.section-card')).toHaveCount(14,{timeout:45_000})
  await page.getByRole('button',{name:'Случайная тренировка',exact:true}).first().click()
  await page.getByLabel('Какие вопросы').selectOption('all')
  await page.getByLabel('Размер подборки').selectOption('20')
  await page.getByRole('button',{name:'Начать тренировку',exact:true}).click()
  await expect(page.locator('.study-bar')).toContainText('Случайная тренировка')
  await expect(page.locator('.question-grid button')).toHaveCount(20)
  const title=await page.locator('#question-title').innerText()
  await page.getByRole('button',{name:'Разобрать с ChatGPT',exact:true}).click()
  const draft=page.getByLabel('Текст сообщения')
  expect(await draft.inputValue()).not.toContain('Верный вариант:')
  expect(await draft.inputValue()).toContain('без раскрытия ответа')
  await draft.fill('Мой редактируемый черновик')
  await page.getByLabel('Что именно хочешь спросить?').fill('Расскажи про механизм')
  await page.getByRole('button',{name:'Закрыть черновик'}).click()
  await page.getByRole('button',{name:'Добавить закладку'}).click()
  await expect(page.getByRole('button',{name:'Убрать закладку'})).toBeVisible()
  await page.getByRole('button',{name:'Далее →',exact:true}).click()
  await expect(page.locator('.study-bar')).toContainText('2 / 20')
  const title2=await page.locator('#question-title').innerText()
  await page.reload()
  await expect(page.locator('#question-title')).toHaveText(title2)
  await page.getByRole('button',{name:/Вопрос 1, не отвечал/}).click()
  await expect(page.locator('#question-title')).toHaveText(title)
  await page.getByRole('button',{name:'Все разделы'}).click()
  await page.getByLabel('Фильтр вопросов').selectOption('bookmarked')
  await expect(page.locator('.search-result')).toHaveCount(1)
  await page.getByRole('button',{name:'Начать повторение'}).click()
  await expect(page.getByRole('status').filter({hasText:'Пока нет вопросов'})).toBeVisible()
  await page.getByLabel('Фильтр вопросов').selectOption('all')
  await page.screenshot({path:'reports/home-desktop.png',fullPage:true})
  await page.getByLabel('Поиск вопросов').fill('2.7')
  await page.locator('.search-result').filter({has:page.getByText('2.7',{exact:true})}).click()
  await expect(page.locator('.illustration img')).toBeVisible()
  await expect.poll(()=>page.locator('.illustration img').evaluate((img:HTMLImageElement)=>img.naturalWidth)).toBeGreaterThan(0)
  await page.getByRole('button',{name:'Увеличить иллюстрацию'}).click()
  await expect(page.getByRole('dialog',{name:'Иллюстрация',exact:true})).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
})
test('ChatGPT action is hidden on Android regardless of viewport changes',async({browser})=> {
  const context=await browser.newContext({userAgent:'Mozilla/5.0 (Linux; Android 14) AppleWebKit/537.36 Chrome/130 Mobile Safari/537.36',viewport:{width:393,height:851},isMobile:true,hasTouch:true})
  const page=await context.newPage()
  await page.goto('/')
  await page.getByLabel('Импортировать архив',{exact:true}).setInputFiles('platform_83_export.zip')
  await expect(page.locator('.section-card')).toHaveCount(14,{timeout:45_000})
  await page.getByRole('button',{name:'Начать изучение'}).first().click()
  await expect(page.getByRole('button',{name:'Разобрать с ChatGPT'})).toHaveCount(0)
  await page.screenshot({path:'reports/question-mobile.png',fullPage:true})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.setViewportSize({width:1200,height:800})
  await expect(page.getByRole('button',{name:'Разобрать с ChatGPT'})).toHaveCount(0)
  await context.close()
})
