import { expect, test } from '@playwright/test'
import { attempts, fixtureZip } from './helpers/cloud'

test('today, charts, rare tags, history and favorite training share existing attempts',async({page})=>{
  await page.setViewportSize({width:393,height:851})
  await page.goto('/')
  await page.getByLabel('Импортировать архив',{exact:true}).setInputFiles(fixtureZip())
  await page.getByRole('button',{name:'Начать изучение'}).first().click()
  await page.getByRole('button',{name:'Добавить закладку'}).click()
  await page.locator('.answers button').first().click()
  await page.getByRole('button',{name:'Ответить заново',exact:true}).click()
  await page.locator('.answers button').nth(3).click()
  await expect(page.getByRole('heading',{name:'✓ Верно',exact:true})).toBeVisible()
  await page.getByText('История ответов (2)',{exact:true}).click()
  await expect(page.locator('.attempt-list li')).toHaveCount(2)

  await page.getByText('Механизмы 1С',{exact:true}).click()
  await page.getByRole('button',{name:'Изменить теги'}).click()
  await page.getByLabel('Основной механизм').selectOption('access')
  await page.getByRole('button',{name:'Сохранить теги'}).click()
  await expect(page.getByText('Права доступа и роли',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Все разделы'}).click()
  await page.getByRole('button',{name:'Статистика',exact:true}).click()
  await expect(page.locator('.today-stats .stat-tile strong')).toHaveText(['1','1','1','1','50%'])
  await page.getByRole('button',{name:'Месяц',exact:true}).click()
  await expect(page.getByRole('group',{name:'Активность',exact:true}).locator('button')).toHaveCount(30)
  await page.getByRole('button',{name:'Всё время',exact:true}).click()
  await expect(page.getByRole('group',{name:'Точность ответов',exact:true}).locator('button')).toHaveCount(1)
  await expect(page.locator('.analytics-table tbody tr')).toHaveCount(2)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.screenshot({path:'reports/statistics-mobile.png',fullPage:true})
  await page.getByRole('button',{name:'Механизмы',exact:true}).click()
  await expect(page.locator('.analytics-table').getByText('Права доступа и роли',{exact:true})).toHaveCount(0)
  await page.getByLabel('Найти вопросы по механизму').selectOption('access')
  await page.getByRole('button',{name:'Открыть вопросы'}).click()
  await page.getByLabel('Фильтр списка').selectOption('errors')
  await expect(page.locator('.collection-row')).toHaveCount(1)
  await page.getByRole('button',{name:'Тренировать тему'}).click()
  await expect(page.locator('.answers button[aria-pressed=true],.explanation')).toHaveCount(0)
  expect(await attempts(page)).toHaveLength(2)
  await page.getByRole('button',{name:'На главную'}).click()
  await page.getByRole('button',{name:'Избранное',exact:true}).click()
  await expect(page.locator('.collection-row')).toHaveCount(1)
  await page.getByRole('button',{name:'Тренировать избранное'}).click()
  await expect(page.locator('.answers button[aria-pressed=true],.explanation')).toHaveCount(0)
  await page.getByRole('button',{name:'На главную'}).click()
  await page.getByRole('button',{name:'Избранное',exact:true}).click()
  await page.getByRole('button',{name:'Убрать закладку'}).click()
  await expect(page.locator('.collection-row')).toHaveCount(0)
  await page.getByRole('button',{name:'Обучение',exact:true}).click()
  await expect(page.getByText(/Сохранённые тренировки/)).toHaveCount(0)
})

test('IndexedDB opening failure presents a recovery screen',async({page})=>{
  await page.addInitScript(()=>{
    indexedDB.open=()=>{throw new DOMException('Storage blocked','SecurityError')}
  })
  await page.goto('/')
  await expect(page.getByRole('heading',{name:'Не удалось открыть локальную базу'})).toBeVisible()
  await expect(page.getByRole('button',{name:'Повторить запуск'})).toBeVisible()
})
