import { test, expect, type Page } from '@playwright/test'
async function attempts(page:Page) {
  return page.evaluate(async()=> {
    const open=indexedDB.open('1c-professional-trainer')
    const db=await new Promise<IDBDatabase>((resolve,reject)=> {open.onsuccess=()=>resolve(open.result);open.onerror=()=>reject(open.error)})
    const tx=db.transaction('attempts');const req=tx.objectStore('attempts').count()
    return new Promise<number>((resolve)=> {req.onsuccess=()=>{db.close();resolve(req.result)}})
  })
}
test('real archive: import, skip, correct key, reload, revisit, retry, reimport',async({page})=> {
  await page.goto('/')
  await page.getByLabel('Импортировать архив',{exact:true}).setInputFiles('platform_83_export.zip')
  await expect(page.getByRole('heading',{name:'Изучение по разделам'})).toBeVisible({timeout:45_000})
  await expect(page.locator('.section-card')).toHaveCount(14)
  await page.getByRole('button',{name:'Начать изучение'}).first().click()
  await expect(page.locator('.answers button')).toHaveCount(5)
  await expect(page.getByRole('region',{name:'Результат ответа'})).toHaveCount(0)
  await expect(page.getByRole('button',{name:'Проверить',exact:true})).toHaveCount(0)
  // Restore a pre-change draft: clicking an already selected variant must also submit.
  const savedChoice=await page.locator('.answers button').nth(3).getAttribute('value')
  await page.evaluate(async answerId=> {
    const request=indexedDB.open('1c-professional-trainer')
    const database=await new Promise<IDBDatabase>(resolve=> {request.onsuccess=()=>resolve(request.result)})
    await new Promise<void>((resolve,reject)=> {
      const tx=database.transaction(['meta','sessions'],'readwrite')
      const meta=tx.objectStore('meta').get('activeSession')
      meta.onsuccess=()=> {const sessions=tx.objectStore('sessions');const get=sessions.get(meta.result.value);get.onsuccess=()=> {const s=get.result;s.choices[s.question_ids[s.cursor]]=answerId;sessions.put(s)}}
      tx.oncomplete=()=>resolve();tx.onerror=()=>reject(tx.error)
    });database.close()
  },savedChoice)
  await page.reload()
  await expect(page.locator('.answers button').nth(3)).toHaveAttribute('aria-pressed','true')
  await page.locator('.answers button').nth(3).click()
  await expect(page.getByRole('heading',{name:'✓ Верно',exact:true})).toBeVisible()
  await expect(page.locator('.answers button').first()).toBeDisabled()
  await page.getByRole('checkbox').click()
  await expect(page.getByRole('checkbox')).toBeChecked()
  await expect(page.getByText('Сохраняем…',{exact:true})).toHaveCount(0)
  await page.reload()
  await expect(page.locator('.answers button').nth(3)).toHaveAttribute('aria-pressed','true')
  await expect(page.getByRole('checkbox')).toBeChecked()
  await page.getByRole('checkbox').click()
  await expect(page.getByRole('checkbox')).not.toBeChecked()
  await expect(page.getByText('Сохраняем…',{exact:true})).toHaveCount(0)
  await expect(page.getByRole('heading',{name:'✓ Верно',exact:true})).toBeVisible()
  await expect(page.getByRole('heading',{name:'Пояснение',exact:true})).toBeVisible()
  await expect(page.locator('.study-bar')).toContainText('1 / 77')
  expect(await attempts(page)).toBe(1)
  await expect(page.locator('html')).toHaveAttribute('data-theme','dark')
  await page.screenshot({path:'reports/question-dark.png',fullPage:true})
  await page.getByRole('combobox',{name:'Тема оформления'}).selectOption('light')
  await expect(page.locator('html')).toHaveAttribute('data-theme','light')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme','light')
  await page.screenshot({path:'reports/question-light.png',fullPage:true})
  await expect(page.getByRole('heading',{name:'✓ Верно',exact:true})).toBeVisible()
  expect(await attempts(page)).toBe(1)
  await page.getByRole('button',{name:'Следующий вопрос',exact:true}).click()
  await page.getByRole('button',{name:'Пропустить',exact:true}).click()
  expect(await attempts(page)).toBe(1)
  await page.getByRole('button',{name:'Вопрос 1, верно',exact:true}).click()
  expect(await attempts(page)).toBe(1)
  await page.getByRole('button',{name:'Ответить заново',exact:true}).click()
  await page.locator('.answers button').first().click()
  await expect(page.getByRole('heading',{name:'Попробуем разобраться'})).toBeVisible()
  expect(await attempts(page)).toBe(2)
  await page.getByRole('button',{name:'Все разделы'}).click()
  await page.getByLabel('Повторный импорт',{exact:true}).setInputFiles('platform_83_export.zip')
  await expect(page.getByRole('status').filter({hasText:'Архив уже загружен'})).toBeVisible()
  expect(await attempts(page)).toBe(2)
  await page.getByRole('combobox',{name:'Тема оформления'}).selectOption('system')
  await page.emulateMedia({colorScheme:'dark'})
  await expect(page.locator('html')).toHaveAttribute('data-theme','dark')
  await page.emulateMedia({colorScheme:'light'})
  await expect(page.locator('html')).toHaveAttribute('data-theme','light')
  expect(await attempts(page)).toBe(2)
  // A dev server must not expose the private archive by URL.
  expect((await page.request.get('/platform_83_export.zip')).status()).toBe(403)
})
