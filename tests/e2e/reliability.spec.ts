import { test, expect } from '@playwright/test'
import { attempts, fixtureZip } from './helpers/cloud'
test('history JSON preview, cancellation, merging and repeated restoration preserve all attempts',async({page})=> {
  await page.goto('/')
  await page.getByLabel('Импортировать архив',{exact:true}).setInputFiles(fixtureZip())
  await page.getByRole('button',{name:'Начать изучение'}).first().click()
  await page.locator('.answers button').nth(4).click()
  await page.getByRole('button',{name:'Все разделы'}).click()
  await page.getByText('Резервная копия истории',{exact:true}).click()
  const download=page.waitForEvent('download')
  await page.getByRole('button',{name:'Скачать историю JSON'}).click()
  const file=await download
  const path=await file.path()
  await page.getByRole('button',{name:'Продолжить обучение'}).click()
  await page.getByRole('button',{name:'Следующий вопрос',exact:true}).click()
  await page.locator('.answers button').first().click()
  await page.getByRole('button',{name:'Все разделы'}).click()
  await page.getByText('Резервная копия истории',{exact:true}).click()
  await page.getByLabel('Загрузить резервную копию').setInputFiles(path!)
  await expect(page.getByRole('region',{name:'Предварительный просмотр копии'})).toContainText('Уже есть: 1')
  await expect(page.getByRole('region',{name:'Предварительный просмотр копии'})).toContainText('Отличаются сохранённые тренировки: 1')
  await page.getByRole('button',{name:'Отмена импорта',exact:true}).click()
  expect(await attempts(page)).toHaveLength(2)
  for(let i=0;i<2;i++) {
    await page.getByLabel('Загрузить резервную копию').setInputFiles(path!)
    await page.getByRole('button',{name:'Объединить историю',exact:true}).click()
    await expect(page.getByRole('status').filter({hasText:'Восстановление завершено'})).toBeVisible()
    expect(await attempts(page)).toHaveLength(2)
  }
})
test('exam hides keys and ChatGPT, persists changed choices, expires after reload and shows separate results',async({page})=> {
  await page.clock.install()
  await page.goto('/')
  await page.getByLabel('Импортировать архив',{exact:true}).setInputFiles(fixtureZip())
  await page.getByRole('button',{name:'Начать пробный экзамен',exact:true}).click()
  await expect(page.getByRole('timer')).toHaveText(/29:|30:/)
  await expect(page.locator('.question-grid button')).toHaveCount(14)
  await page.locator('.answers button').first().click()
  await page.locator('.answers button').nth(4).click()
  await expect(page.locator('.answers button').nth(4)).toHaveAttribute('aria-pressed','true')
  expect(await attempts(page)).toHaveLength(0)
  await expect(page.getByRole('button',{name:'Разобрать с ChatGPT'})).toHaveCount(0)
  await expect(page.getByText('Пояснение',{exact:true})).toHaveCount(0)
  await expect(page.locator('.correct,.incorrect,.answer-mark')).toHaveCount(0)
  await page.reload()
  await expect(page.locator('.answers button').nth(4)).toHaveAttribute('aria-pressed','true')
  await page.screenshot({path:'reports/exam-in-progress.png',fullPage:true})
  await page.clock.fastForward(30*60_000+1000)
  await expect(page.getByRole('heading',{name:'Не сдано',exact:true})).toBeVisible()
  await expect(page.getByText('Правильных ответов: 1 из 14',{exact:true})).toBeVisible()
  await expect(page.locator('.exam-review')).toHaveCount(14)
  await page.locator('.exam-review summary').first().click()
  await expect(page.locator('.exam-review').first().getByRole('heading',{name:'Пояснение',exact:true})).toBeVisible()
  expect(await attempts(page)).toHaveLength(1)
  await page.getByRole('button',{name:'Все разделы'}).click()
  await expect(page.locator('.progress-card strong')).toContainText('0')
  await expect(page.getByText('Результаты экзаменов (1)',{exact:true})).toBeVisible()
})
test('exam accepts keyboard choices and requires an explicit early finish on mobile',async({page})=> {
  await page.setViewportSize({width:393,height:851})
  await page.goto('/')
  await page.getByLabel('Импортировать архив',{exact:true}).setInputFiles(fixtureZip())
  await page.getByRole('button',{name:'Начать пробный экзамен',exact:true}).click()
  const options=page.locator('.answers button')
  await options.first().focus()
  await page.keyboard.press('Tab')
  await expect(options.nth(1)).toBeFocused()
  await page.keyboard.press('Enter')
  const next=page.getByRole('button',{name:'Следующий вопрос',exact:true})
  await expect(next).toBeFocused()
  const r=await next.boundingBox();expect(r!.y+r!.height).toBeGreaterThan(811)
  await page.keyboard.press('Enter')
  await expect(options.first()).toBeFocused()
  await expect(page.locator('.study-bar')).toContainText('2 / 14')
  await page.getByRole('button',{name:'Завершить экзамен',exact:true}).click()
  await expect(page.getByRole('group',{name:'Подтверждение завершения'})).toContainText('Без ответа: 13')
  await page.getByRole('button',{name:'Продолжить экзамен',exact:true}).click()
  expect(await attempts(page)).toHaveLength(0)
  await page.getByRole('button',{name:'Завершить экзамен',exact:true}).click()
  await page.getByRole('button',{name:'Завершить и показать результат',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Не сдано',exact:true})).toBeVisible()
  expect(await attempts(page)).toHaveLength(1)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})
