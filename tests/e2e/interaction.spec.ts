import { test, expect, type Page } from '@playwright/test'
async function openStudy(page:Page) {
  await page.goto('/')
  await page.getByLabel('Импортировать архив',{exact:true}).setInputFiles('platform_83_export.zip')
  await expect(page.locator('.section-card')).toHaveCount(14,{timeout:45_000})
  await page.getByRole('button',{name:'Начать изучение'}).first().click()
  await expect(page.locator('.answers button')).toHaveCount(5)
}
async function countAttempts(page:Page) {
  return page.evaluate(async()=> {
    const request=indexedDB.open('1c-professional-trainer')
    const database=await new Promise<IDBDatabase>(resolve=> {request.onsuccess=()=>resolve(request.result)})
    const req=database.transaction('attempts').objectStore('attempts').count()
    return new Promise<number>(resolve=> {req.onsuccess=()=>{database.close();resolve(req.result)}})
  })
}
test('Tab and Enter choose any answer, focus advances safely, held Enter does not navigate',async({page})=> {
  await openStudy(page)
  const options=page.locator('.answers button')
  for(let i=0;i<40;i++) {
    if(await options.first().evaluate(el=>el===document.activeElement)) break
    await page.keyboard.press('Tab')
  }
  await expect(options.first()).toBeFocused()
  for(let i=0;i<4;i++) await page.keyboard.press('Tab')
  await expect(options.nth(4)).toBeFocused()
  expect(await countAttempts(page)).toBe(0)
  await page.screenshot({path:'reports/keyboard-focus.png'})
  await page.keyboard.down('Enter')
  await expect(page.getByRole('heading',{name:'✓ Верно',exact:true})).toBeVisible()
  const next=page.getByRole('button',{name:'Следующий вопрос',exact:true})
  await expect(next).toBeFocused()
  await page.keyboard.down('Enter')
  await page.keyboard.down('Enter')
  await expect(page.locator('.study-bar')).toContainText('1 / 77')
  expect(await countAttempts(page)).toBe(1)
  await page.keyboard.up('Enter')
  await page.keyboard.press('Enter')
  await expect(page.locator('.study-bar')).toContainText('2 / 77')
  await expect(options.first()).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(options.nth(1)).toBeFocused()
  await page.keyboard.press('Space')
  await expect(next).toBeFocused()
  expect(await countAttempts(page)).toBe(2)
  await page.keyboard.press('Enter')
  await expect(page.locator('.study-bar')).toContainText('3 / 77')
  await expect(options.first()).toBeFocused()
  await page.keyboard.press('4')
  await expect(next).toBeFocused()
  expect(await countAttempts(page)).toBe(3)
})
test('mobile next button stays within thumb reach during scroll and never advances on its own',async({browser})=> {
  const context=await browser.newContext({viewport:{width:393,height:851},isMobile:true,hasTouch:true,userAgent:'Mozilla/5.0 (Linux; Android 14) AppleWebKit/537.36 Chrome/130 Mobile Safari/537.36'})
  const page=await context.newPage()
  await openStudy(page)
  const next=page.getByRole('button',{name:'Следующий вопрос',exact:true})
  await expect(next).toBeDisabled()
  await page.locator('.answers button').nth(4).click()
  await expect(next).toBeEnabled()
  await expect(page.locator('.study-bar')).toContainText('1 / 77')
  for(const at of [0,500,1200]) {
    await page.evaluate(y=>scrollTo(0,y),at)
    const r=await next.boundingBox()
    expect(r).not.toBeNull()
    expect(r!.height).toBeGreaterThanOrEqual(48)
    expect(r!.y+r!.height).toBeLessThanOrEqual(851)
    expect(r!.y+r!.height).toBeGreaterThan(851-40)
    expect(await next.evaluate(el=> {
      const r=el.getBoundingClientRect()
      return document.elementFromPoint(r.x+r.width/2,r.y+r.height/2)?.closest('button')===el
    })).toBe(true)
  }
  await page.evaluate(()=>scrollTo(0,500))
  await page.screenshot({path:'reports/mobile-bottom-next.png'})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await next.click()
  await expect(page.locator('.study-bar')).toContainText('2 / 77')
  await expect(next).toBeDisabled()
  await expect(page.locator('#question-title')).toBeInViewport()
  expect(await countAttempts(page)).toBe(1)
  await page.setViewportSize({width:393,height:568})
  await page.locator('.answers button').first().click()
  await expect(next).toBeEnabled()
  const r=await next.boundingBox()
  expect(r!.y+r!.height).toBeLessThanOrEqual(568)
  expect(r!.y+r!.height).toBeGreaterThan(528)
  await context.close()
})
