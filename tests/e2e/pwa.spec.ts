import { test, expect } from '@playwright/test'
import { attempts, bind, fixtureZip, login, SyntheticAPI } from './helpers/cloud'
const base=process.env.VITE_BASE_PATH??'/'
test('production offline restart retains all real illustrations and mobile next stays at the bottom',async({browser})=> {
  const context=await browser.newContext({baseURL:'http://127.0.0.1:4175',viewport:{width:393,height:851},isMobile:true,hasTouch:true,userAgent:'Mozilla/5.0 (Linux; Android 14) AppleWebKit/537.36 Chrome/130 Mobile Safari/537.36'})
  const page=await context.newPage()
  await context.route('https://**.supabase.co/**',route=>route.abort())
  await page.goto(base)
  await page.getByLabel('Импортировать архив',{exact:true}).setInputFiles('platform_83_export.zip')
  await expect(page.locator('.section-card')).toHaveCount(14,{timeout:45_000})
  await page.evaluate(async()=>{await navigator.serviceWorker.ready})
  await page.getByLabel('Поиск вопросов').fill('2.7')
  await page.locator('.search-result').filter({has:page.getByText('2.7',{exact:true})}).click()
  await expect(page.locator('.illustration img')).toBeVisible()
  await context.setOffline(true)
  await page.reload()
  await expect(page.locator('.illustration img')).toBeVisible()
  expect(await page.locator('.illustration img').evaluate((img:HTMLImageElement)=>img.naturalWidth)).toBeGreaterThan(0)
  await page.getByRole('button',{name:'Увеличить иллюстрацию'}).click()
  await expect(page.getByRole('dialog',{name:'Иллюстрация',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Закрыть',exact:true}).click()
  await page.locator('.answers button').first().click()
  const next=page.getByRole('button',{name:'Следующий вопрос',exact:true}),rect=await next.boundingBox()
  expect(rect!.y+rect!.height).toBeGreaterThan(811)
  expect(rect!.y+rect!.height).toBeLessThanOrEqual(851)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.screenshot({path:'reports/pwa-offline-mobile.png',fullPage:true})
  await context.close()
})
test('production PWA reopens offline with private bank, queues answers, syncs on reconnect and keeps logout gate',async({page,context})=> {
  const api=new SyntheticAPI(true)
  await api.connect(context)
  await page.goto(base)
  await page.getByLabel('Импортировать архив',{exact:true}).setInputFiles(fixtureZip())
  await login(page);await bind(page)
  await page.evaluate(async()=>{await navigator.serviceWorker.ready})
  await page.getByRole('button',{name:'Начать изучение'}).first().click()
  await page.locator('.answers button').nth(4).click()
  await expect(page.locator('.cloud-bar [role=status]')).toHaveText('Синхронизировано',{timeout:30_000})
  await page.getByRole('button',{name:'Следующий вопрос',exact:true}).click()
  await context.setOffline(true)
  // Routes are bypassed in offline mode to exercise real network failure.
  await context.unroute('https://**.supabase.co/**')
  await page.reload()
  await expect(page.getByRole('button',{name:'Продолжить офлайн на этом устройстве',exact:true})).toBeVisible({timeout:30_000})
  await page.getByRole('button',{name:'Продолжить офлайн на этом устройстве',exact:true}).click()
  await expect(page.locator('.answers button')).toHaveCount(5)
  await page.locator('.answers button').first().click()
  expect(await attempts(page)).toHaveLength(2)
  await page.getByRole('button',{name:'Все разделы'}).click()
  await page.getByText('Установка и работа без сети',{exact:false}).click()
  await expect(page.getByText(/Оболочка приложения сохранена/)).toBeVisible()
  const keys=await page.evaluate(async()=>{const names=await caches.keys();return (await Promise.all(names.map(async name=>(await (await caches.open(name)).keys()).map(r=>r.url)))).flat()})
  expect(keys.length).toBeGreaterThan(5)
  expect(keys.every(url=>new URL(url).origin===new URL(page.url()).origin)).toBe(true)
  expect(keys.some(url=>/supabase|token|question|zip|history/.test(url))).toBe(false)
  const reopened=await context.newPage()
  await page.close()
  await reopened.goto(base)
  await reopened.getByRole('button',{name:'Продолжить офлайн на этом устройстве',exact:true}).click()
  expect(await attempts(reopened)).toHaveLength(2)
  await api.connect(context);await context.setOffline(false)
  await reopened.getByRole('button',{name:'Повторить синхронизацию',exact:true}).click()
  await expect(reopened.locator('.cloud-bar [role=status]')).toHaveText('Синхронизировано',{timeout:30_000})
  expect(Object.keys(api.attempts)).toHaveLength(2)
  await reopened.getByRole('button',{name:'Аккаунт',exact:true}).click()
  await reopened.getByRole('button',{name:'Выйти из аккаунта',exact:true}).click()
  await expect(reopened.getByLabel('Email аккаунта тренажёра',{exact:true})).toBeVisible()
  await context.setOffline(true);await context.unroute('https://**.supabase.co/**')
  await reopened.reload()
  await expect(reopened.getByRole('button',{name:'Продолжить офлайн на этом устройстве',exact:true})).toHaveCount(0)
  await expect(reopened.locator('.answers button,.section-card')).toHaveCount(0)
})
