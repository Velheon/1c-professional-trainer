import {test,expect} from '@playwright/test'
import {attempts,fixtureZip} from './helpers/cloud'
test('review and random open clean, ordinary navigation shows history and retry clears it',async({page})=>{
 await page.goto('/')
 await page.getByLabel('Импортировать архив',{exact:true}).setInputFiles(fixtureZip())
 await page.getByRole('button',{name:'Начать изучение'}).first().click()
 await page.locator('.answers button').first().click()
 await expect(page.getByRole('region',{name:'Результат ответа'})).toBeVisible()
 await page.getByRole('button',{name:'Все разделы'}).click()
 await page.getByRole('button',{name:'Начать повторение'}).click()
 await expect(page.locator('.answers button[aria-pressed=true]')).toHaveCount(0)
 await expect(page.locator('.correct,.incorrect,.explanation')).toHaveCount(0)
 expect(await attempts(page)).toHaveLength(1)
 await page.getByRole('button',{name:'Разобрать с ChatGPT',exact:true}).click()
 expect(await page.getByLabel('Текст сообщения').inputValue()).not.toContain('Верный вариант:')
 await page.getByRole('button',{name:'Закрыть черновик'}).click()
 await page.locator('.answers button').nth(3).click()
 await expect(page.getByRole('heading',{name:'✓ Верно',exact:true})).toBeVisible()
 expect(await attempts(page)).toHaveLength(2)
 await page.reload()
 await expect(page.getByRole('heading',{name:'✓ Верно',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Все разделы'}).click()
 await page.getByRole('button',{name:'Случайная тренировка',exact:true}).first().click()
 await page.getByRole('button',{name:'Начать тренировку',exact:true}).click()
 await expect(page.locator('.answers button[aria-pressed=true],.explanation,.correct')).toHaveCount(0)
 expect(await attempts(page)).toHaveLength(2)
 await page.locator('.answers button').first().click()
 await expect(page.getByText('Требует повторения',{exact:true})).toBeVisible()
 expect(await attempts(page)).toHaveLength(3)
 await page.getByRole('button',{name:'Все разделы'}).click()
 await page.getByLabel('Поиск вопросов').fill('1.1')
 await page.locator('.search-result').first().click()
 await expect(page.getByRole('region',{name:'Результат ответа'})).toBeVisible()
 await page.getByRole('button',{name:'Ответить заново',exact:true}).click()
 await expect(page.locator('.answers button[aria-pressed=true],.explanation,.correct')).toHaveCount(0)
 expect(await attempts(page)).toHaveLength(3)
})
test('compound references use original codes while preserving order and the original key',async({page})=>{
 await page.goto('/')
 await page.getByLabel('Импортировать архив',{exact:true}).setInputFiles('platform_83_export.zip')
 await expect(page.locator('.section-card')).toHaveCount(14,{timeout:45000})
 await page.getByLabel('Поиск вопросов').fill('1.11')
 await page.locator('.search-result').first().click()
 await expect(page.locator('.answer-number')).toHaveText(['1','2','3','4','5','6'])
 await page.locator('.answers button').last().click()
 await expect(page.getByRole('heading',{name:'✓ Верно',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Разобрать с ChatGPT',exact:true}).click()
 expect(await page.getByLabel('Текст сообщения').inputValue()).toContain('Верный вариант: 6')
})
