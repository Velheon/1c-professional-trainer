import { test, expect } from '@playwright/test'
import { SyntheticAPI, fixtureZip, login, bind, attempts } from './helpers/cloud'
test('cloud client with synthetic API: explicit transfer, two devices, retry, logout and foreign-account gate',async({page,browser})=> {
  const api=new SyntheticAPI()
  await api.connect(page.context())
  await page.goto('/')
  await page.getByLabel('Импортировать архив',{exact:true}).setInputFiles(fixtureZip())
  await expect(page.locator('.section-card')).toHaveCount(2)
  await page.getByRole('button',{name:'Начать изучение'}).first().click()
  await page.locator('.answers button').nth(3).click()
  await expect(page.getByRole('heading',{name:'✓ Верно',exact:true})).toBeVisible()
  const original=(await attempts(page))[0]
  await login(page)
  await expect(page.getByRole('checkbox',{name:/Привязать этот браузер/})).toBeVisible()
  expect(Object.keys(api.attempts)).toHaveLength(0)
  await bind(page)
  expect(Object.keys(api.attempts)).toEqual([original.attempt_id])
  expect((await attempts(page))[0].attempt_id).toBe(original.attempt_id)
  await page.reload()
  await expect(page.getByRole('heading',{name:'✓ Верно',exact:true})).toBeVisible()
  const second=await browser.newContext({baseURL:'http://127.0.0.1:5174'})
  await api.connect(second)
  const b=await second.newPage()
  await b.goto('/')
  await login(b);await bind(b)
  await expect(b.getByRole('button',{name:'Продолжить здесь',exact:true})).toBeVisible()
  await b.getByRole('button',{name:'Продолжить здесь',exact:true}).click()
  await expect(b.getByRole('heading',{name:'✓ Верно',exact:true})).toBeVisible()
  expect(await attempts(b)).toHaveLength(1)
  await b.getByRole('button',{name:'Ответить заново',exact:true}).click()
  await b.locator('.answers button').first().click()
  await expect(b.locator('.cloud-bar [role=status]')).toHaveText('Синхронизировано',{timeout:30_000})
  await expect.poll(()=>Object.keys(api.attempts).length).toBe(2)
  await page.getByRole('button',{name:'Повторить синхронизацию',exact:true}).click()
  await expect.poll(async()=>(await attempts(page)).length).toBe(2)
  expect(new Set((await attempts(page)).map(a=>a.device_id)).size).toBe(2)
  await page.getByRole('button',{name:'Аккаунт',exact:true}).click()
  let releaseLogout!:()=>void
  api.logoutBarrier=new Promise<void>(resolve=>{releaseLogout=resolve})
  await page.getByRole('button',{name:'Выйти из аккаунта',exact:true}).click()
  await expect(page.locator('.auth-screen')).toBeVisible()
  await expect(page.locator('.answers button')).toHaveCount(0)
  releaseLogout();api.logoutBarrier=null
  await expect(page.getByLabel('Email аккаунта тренажёра',{exact:true})).toBeVisible()
  await expect(page.getByRole('button',{name:'Продолжить офлайн на этом устройстве',exact:true})).toHaveCount(0)
  await expect(page.locator('.section-card')).toHaveCount(0)
  await expect(page.locator('.answers button')).toHaveCount(0)
  expect(await attempts(page)).toHaveLength(2)
  await login(page,'outsider@example.invalid')
  await expect(page.getByText(/История этого браузера принадлежит другому аккаунту/)).toBeVisible()
  await expect(page.locator('.section-card')).toHaveCount(0)
  await expect(page.locator('.answers button')).toHaveCount(0)
  await page.screenshot({path:'reports/cloud-account-protection.png'})
  await page.getByRole('button',{name:'Выйти из аккаунта',exact:true}).click()
  await expect(page.getByLabel('Email аккаунта тренажёра',{exact:true})).toBeVisible()
  await login(page)
  await expect(page.locator('.cloud-bar')).toBeVisible()
  await expect(page.getByRole('checkbox',{name:/Привязать этот браузер/})).toHaveCount(0)
  expect(await attempts(page)).toHaveLength(2)
  await second.close()
})
